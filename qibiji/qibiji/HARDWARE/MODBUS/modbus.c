////////*16位CRC校验函数,查表法*////////////////
u16 crc16(u8 *puchMsg,u16 usDataLen) 	
{ 											
	u8 uchCRCHi = 0xFF ; 				
	u8 uchCRCLo = 0xFF ; 				
	u16 uIndex ; 							
	while (usDataLen--) 					
	{
		uIndex = uchCRCHi ^ *puchMsg++ ; 	
		uchCRCHi = uchCRCLo ^ auchCRCHi[uIndex] ;
		uchCRCLo = auchCRCLo[uIndex] ;
	}
	return (((u16)(uchCRCHi) << 8) | uchCRCLo) ;
}

//字节转整数
u16 CharToInt(u8 *pChar)   
{
	u16 i,j,data;
	i = pChar[0];
	j = pChar[1];
	data = ((i << 8) & 0xff00) | (j & 0x00ff);
	return data;
}

//数据发送
u8 Rs485_TxData(u8 *buf)
{
	u8  err;
	u16 i=0,len;
	
	err = 0;
	len = ((u16)buf[2] << 8) + buf[3]-2;
	for(i = 0; i<len;i++)
	{
		DMA_Tx_Buf5[i] = buf[i+4];
	}
	
	switch(buf[1])
	{
		case 0x01:  //uart1
			Usart1_Send((char *)DMA_Tx_Buf5,len);
			break;
		case 0x02:  //uart4  //rs485-1
			Usart4_Send(DMA_Tx_Buf5,len);
			break;
		case 0x03:  //uart5  //rs485-2
			Usart5_Send(DMA_Tx_Buf5,len);
			break;
		default:
			err = 0x01;
			break;
	}
	return err;
}

